#!/usr/bin/env node
/**
 * Builds the responsive screenshot derivatives the landing page actually
 * serves.
 *
 * Sources live in `assets/shots-src/` (outside `public/`, so the ~14MB of
 * full-resolution PNGs never reach the deploy). This writes downscaled
 * AVIF + WebP into `public/assets/shots/`, plus a typed manifest at
 * `src/components/landing/shots.gen.ts` so components get exact intrinsic
 * dimensions without hand-maintaining them.
 *
 * Requires ImageMagick 7 (`brew install imagemagick`).
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const srcDir = join(root, 'assets/shots-src');
const outDir = join(root, 'public/assets/shots');
const publicPrefix = '/assets/shots';
const manifestPath = join(root, 'src/components/landing/shots.gen.ts');

/**
 * Widest CSS box any shot paints into is ~784px (a split-media section at the
 * 840px single-column breakpoint); the quilted gallery's two-column tile is
 * ~744px. 1600 covers both at 2x DPR, 1024 covers the one-column gallery tile
 * and phones at 2x, 640 covers phones at 1x.
 */
const WIDTHS = [640, 1024, 1600];

const FORMATS = [
  { ext: 'avif', args: ['-quality', '58'] },
  { ext: 'webp', args: ['-quality', '82', '-define', 'webp:method=6'] },
];

const magick = (args) => execFileSync('magick', args, { encoding: 'utf8' });

const identify = (file) => {
  const [width, height] = magick(['identify', '-format', '%w %h', file])
    .trim()
    .split(' ')
    .map(Number);
  return { width, height };
};

const bytes = (file) => statSync(file).size;

const kb = (n) => `${(n / 1024).toFixed(0)}kB`;

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const sources = readdirSync(srcDir)
  .filter((f) => f.endsWith('.png'))
  .sort();

if (sources.length === 0) {
  throw new Error(`No source PNGs found in ${srcDir}`);
}

const entries = [];
let srcTotal = 0;
let outTotal = 0;

for (const file of sources) {
  const name = basename(file, '.png');
  const srcPath = join(srcDir, file);
  const source = identify(srcPath);
  srcTotal += bytes(srcPath);

  // Never upscale: cap at the source width, and keep at least one derivative
  // for sources narrower than the smallest target (the portrait mobile shots).
  const targets = WIDTHS.filter((w) => w < source.width);
  targets.push(Math.min(source.width, WIDTHS[WIDTHS.length - 1]));
  const widths = [...new Set(targets)].sort((a, b) => a - b);

  const variants = [];

  for (const width of widths) {
    for (const { ext, args } of FORMATS) {
      const outName = `${name}-${width}.${ext}`;
      const outPath = join(outDir, outName);
      magick([
        srcPath,
        '-strip',
        '-colorspace',
        'sRGB',
        '-depth',
        '8',
        '-filter',
        'Lanczos',
        '-resize',
        `${width}x`,
        ...args,
        outPath,
      ]);
      outTotal += bytes(outPath);
      variants.push({ width, ext, url: `${publicPrefix}/${outName}` });
    }
  }

  const largest = Math.max(...widths);
  const intrinsic = identify(
    join(outDir, `${name}-${largest}.webp`),
  );

  const srcSetFor = (ext) =>
    variants
      .filter((v) => v.ext === ext)
      .map((v) => `${v.url} ${v.width}w`)
      .join(', ');

  entries.push({
    name,
    width: intrinsic.width,
    height: intrinsic.height,
    src: `${publicPrefix}/${name}-${largest}.webp`,
    avifSrcSet: srcSetFor('avif'),
    webpSrcSet: srcSetFor('webp'),
  });

  console.log(
    `${name.padEnd(22)} ${source.width}x${source.height} ${kb(bytes(srcPath)).padStart(7)}` +
      ` -> ${widths.join('/')}w` +
      ` (avif ${kb(bytes(join(outDir, `${name}-${largest}.avif`)))},` +
      ` webp ${kb(bytes(join(outDir, `${name}-${largest}.webp`)))} at ${largest}w)`,
  );
}

const body = entries
  .map(
    (e) => `  '${e.name}': {
    width: ${e.width},
    height: ${e.height},
    src: '${e.src}',
    avifSrcSet:
      '${e.avifSrcSet}',
    webpSrcSet:
      '${e.webpSrcSet}',
  },`,
  )
  .join('\n');

writeFileSync(
  manifestPath,
  `// AUTO-GENERATED by scripts/optimize-shots.mjs — do not edit.
// Regenerate with \`npm run shots\` after changing anything in assets/shots-src/.

export interface Shot {
  /** Intrinsic size of the largest derivative — reserves the aspect box. */
  readonly width: number;
  readonly height: number;
  /** Fallback src for browsers that ignore srcSet. */
  readonly src: string;
  readonly avifSrcSet: string;
  readonly webpSrcSet: string;
}

export const shots = {
${body}
} as const satisfies Record<string, Shot>;

export type ShotName = keyof typeof shots;
`,
);

console.log(
  `\n${sources.length} shots: ${kb(srcTotal)} of source PNG -> ${kb(outTotal)} across ` +
    `${readdirSync(outDir).length} derivatives.`,
);
console.log(`Manifest written to ${manifestPath.replace(root, '')}`);
